/* 察合台文（阿拉伯字母）↔ 逐字母换写。
   两栏编辑器（js/editors/two-pane.js）通用的转换接口，写法见 js/converters/_template.js。 */
(function () {
  const NNBSP = ' ', MVS = '᠎';
  const chg = (() => {
    const S2L = { 'ا': 'ʾ', 'آ': 'ā', 'أ': 'ʾ', 'إ': 'ʾ', 'ب': 'b', 'پ': 'p', 'ت': 't', 'ث': 's̱', 'ج': 'c', 'چ': 'č', 'ح': 'ḥ', 'خ': 'ḫ',
      'د': 'd', 'ذ': 'ẕ', 'ر': 'r', 'ز': 'z', 'ژ': 'ž', 'س': 's', 'ش': 'š', 'ص': 'ṣ', 'ض': 'ż', 'ط': 'ṭ', 'ظ': 'ẓ', 'ع': 'ʿ', 'غ': 'ġ',
      'ف': 'f', 'ق': 'q', 'ك': 'k', 'ک': 'k', 'گ': 'g', 'ڭ': 'ñ', 'ل': 'l', 'م': 'm', 'ن': 'n', 'و': 'w', 'ؤ': 'ʼw', 'ه': 'h', 'ة': 'ẗ',
      'ی': 'y', 'ي': 'y', 'ى': 'y', 'ئ': 'ʼy', 'ء': 'ʼ',
      'َ': 'a', 'ِ': 'i', 'ُ': 'u', 'ْ': '°', 'ّ': '~',
      '،': ',', '؛': ';', '؟': '?' };
    const L2S = [['ʼy', 'ئ'], ['ʼw', 'ؤ'], ['s̱', 'ث'], ['X', 'ش'], ['C', 'چ'], ['G', 'غ'], ['J', 'ژ'],
      ['ʾ', 'ا'], ["'", 'ا'], ['ā', 'آ'], ['b', 'ب'], ['p', 'پ'], ['t', 'ت'], ['c', 'ج'], ['j', 'ج'], ['č', 'چ'], ['ḥ', 'ح'], ['H', 'ح'],
      ['ḫ', 'خ'], ['x', 'خ'], ['d', 'د'], ['ẕ', 'ذ'], ['r', 'ر'], ['z', 'ز'], ['ž', 'ژ'], ['s', 'س'], ['š', 'ش'], ['ṣ', 'ص'], ['S', 'ص'],
      ['ż', 'ض'], ['D', 'ض'], ['ṭ', 'ط'], ['T', 'ط'], ['ẓ', 'ظ'], ['Z', 'ظ'], ['ʿ', 'ع'], ['`', 'ع'], ['ġ', 'غ'], ['f', 'ف'], ['q', 'ق'],
      ['k', 'ک'], ['g', 'گ'], ['ñ', 'ڭ'], ['N', 'ڭ'], ['l', 'ل'], ['m', 'م'], ['n', 'ن'], ['w', 'و'], ['v', 'و'], ['h', 'ه'], ['ẗ', 'ة'],
      ['y', 'ی'], ['ʼ', 'ء'], ['^', 'ء'], ['a', 'َ'], ['i', 'ِ'], ['u', 'ُ'], ['°', 'ْ'], ['~', 'ّ'],
      [',', '،'], [';', '؛'], ['?', '؟']];
    function toScript(src) {
      const s = src.normalize('NFC'); let out = '', i = 0;
      outer: while (i < s.length) {
        for (const [k, v] of L2S) if (s.startsWith(k, i)) { out += v; i += k.length; continue outer; }
        const ch = s[i]; i++;
        out += ch >= '0' && ch <= '9' ? String.fromCharCode(0x06F0 + (+ch)) : ch;
      }
      return out;
    }
    function toLatin(src) {
      let out = '';
      for (const ch of src.normalize('NFC')) {
        const c = ch.charCodeAt(0);
        if (S2L[ch] !== undefined) out += S2L[ch];
        else if (c >= 0x06F0 && c <= 0x06F9) out += String(c - 0x06F0);
        else if (c >= 0x0660 && c <= 0x0669) out += String(c - 0x0660);
        else if (ch === '‌') out += '|';
        else out += ch;
      }
      return out.normalize('NFC');
    }
    return {
      toScript, toLatin,
      WORD: { m: /[ء-ْٰ-ۓ‌]/, l: /[A-Za-zʾʿʼāčḥḫẕžšṣżṭẓġñẗ̀-ͯ~°'`^|]/ },
      UI: {
        name: '察合台文', lang: 'chg', schemes: null, latinSub: '逐字母换写，可用 ASCII 简写',
        sampleScript: 'هر کیم که وفا قیلسه وفا تاپقوسیدور\nهر کیم که جفا قیلسه جفا تاپقوسیدور\n\nتورکی تیل',
        notes: [
          '左右两栏都可以编辑，改动一侧，另一侧随即重写。拉丁一栏是逐字母换写，不补写元音：ا 记 ʾ，و 记 w，ی 记 y，所以 قیلسه 换写为 qylsh。需要标出短元音时，开合符号分别记 a、i、u，静符记 °，叠音符记 ~。',
          '特殊字母：ث s̱、ح ḥ、خ ḫ、ذ ẕ、ص ṣ、ض ż、ط ṭ、ظ ẓ、ع ʿ、غ ġ、ڭ ñ、ء ʼ。键盘不便时可以打简写：\' 打 ا，` 打 ع，^ 打 ء，x 打 خ，大写 X C G J 打 ش چ غ ژ，大写 S D T Z H N 打 ص ض ط ظ ح ڭ。sh、kh 这类两个字母不会合成一个，因为 س+ه、ک+ه 本身常见。',
          'ك 和 ک、ي 和 ی 都读作 k、y，从拉丁字母转回时一律用波斯式写法 ک、ی。']
      }
    };
  })();
  SIYI.converters.chg = chg;
})();
